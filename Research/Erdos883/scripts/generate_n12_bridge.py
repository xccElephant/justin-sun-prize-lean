"""Generate ordinary Lean clause proofs for the pinned n12 CNF.

This script is untrusted: output must typecheck against `formula`, which is
parsed independently by Mathlib from the original archived DIMACS bytes.
The certificate and blocking cycles are due to Cecil Jentges (source b5738d8).
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
DEST = ROOT / 'Research/Erdos883/N12Clauses.lean'
cnf = ROOT / 'verification/2026-10-20-bounty-only/certificates/n12_b0_l2.cnf'
archived = [list(map(int, line.split()))[:-1] for line in cnf.read_text().splitlines()[1:]]
clauses = []
proofs = []

def add(cl, pr):
    clauses.append(cl)
    proofs.append(pr)

# First four equal-support prefixes.
for x,y in [(4,2),(8,4),(9,3),(12,6)]:
    add([-x,y], f'by\n    change {x} ∈ B → (¬ {y} ∈ B) → False\n    intro hx hn\n    exact hn (hp {x} hx {y} (by decide) (by decide) (by support_facts))')
# The six parity-preserving support enlargements.
for x,y in [(1,9),(1,5),(1,7),(1,11),(2,12),(2,10)]:
    add([-x,y], f'by\n    change {x} ∈ B → (¬ {y} ∈ B) → False\n    intro hx hn\n    exact hn (hs {x} hx {y} (by decide) (by decide) (by support_facts))')

nextvar = 12
for positive,k,bound in [(True,9,'hpos'),(False,3,'hneg')]:
    p = '(fun k => k + 1 ∈ B)' if positive else '(fun k => k + 1 ∉ B)'
    def inp(i): return f'{i+1} ∈ B' if positive else f'¬ {i+1} ∈ B'
    def x(i): return i+1 if positive else -(i+1)
    s=[]
    for i in range(12):
        s.append(list(range(nextvar+1,nextvar+k+1)))
        nextvar+=k
    # Negating a negative input in the CNF gives double-negation in `satisfies`.
    # Satisfies uses v.neg: +x falsified = ¬mem; -x falsified = mem.
    # Therefore the generated positive literal x for complement input supplies ¬mem directly.
    add([-x(0),s[0][0]], f'by\n    change ({inp(0)}) → (¬ aux {p} 1 0) → False\n    intro hx hn\n    exact hn (aux_of_true {p} hx)')
    for j in range(1,k):
        add([-s[0][j]], f'by\n    change aux {p} 1 {j} → False\n    exact aux_one_higher {p} (by decide)')
    for i in range(1,12):
        add([-x(i),s[i][0]], f'by\n    change ({inp(i)}) → (¬ aux {p} {i+1} 0) → False\n    intro hx hn\n    exact hn (aux_of_true {p} hx)')
        add([-s[i-1][0],s[i][0]], f'by\n    change aux {p} {i} 0 → (¬ aux {p} {i+1} 0) → False\n    intro hx hn\n    exact hn (aux_propagate {p} hx)')
        for j in range(1,k):
            add([-x(i),-s[i-1][j-1],s[i][j]], f'by\n    change ({inp(i)}) → aux {p} {i} {j-1} → (¬ aux {p} {i+1} {j}) → False\n    intro hx hh hn\n    exact hn (aux_increment {p} hx hh)')
            add([-s[i-1][j],s[i][j]], f'by\n    change aux {p} {i} {j} → (¬ aux {p} {i+1} {j}) → False\n    intro hx hn\n    exact hn (aux_propagate {p} hx)')
        add([-x(i),-s[i-1][k-1]], f'by\n    change ({inp(i)}) → aux {p} {i} {k-1} → False\n    intro hx hh\n    exact aux_no_overflow {p} {bound} (by decide : {i} < 12) hx hh')

for v in range(2,13,2):
    add([v], f'by\n    change (¬ {v} ∈ B) → False\n    intro hn\n    exact hn (hevens {v} (by decide))')

blocks = [([5,4,7,11],[5,2,7,4,11]),([3,4,5,7],[3,2,5,4,7]),
          ([9,4,5],[3,2,9,4,5]),([7,4,9],[7,2,3,4,9]),
          ([3,4,11,5],[3,2,11,4,5]),([9,4,11],[3,2,9,4,11]),
          ([3,4,11,7],[3,2,11,4,7])]
for lits,cyc in blocks:
    typ=' → '.join([f'{v} ∈ B' for v in lits]+['False'])
    pr=f'by\n    change {typ}\n    intro '+' '.join(f'h{v}' for v in lits)+'\n'
    for v,x in [(2,4),(3,9)]:
        if v in cyc and v not in lits:
            pr+=f'    have h{v} : {v} ∈ B := hp {x} h{x} {v} (by decide) (by decide) (by support_facts)\n'
    aset='{'+', '.join(map(str,cyc))+'}'
    vector='!['+', '.join(map(str,cyc))+']'
    pr+='    apply hfree\n'
    pr+=f'    apply cycleWitness_isContained_of_subset (A := {aset}) (c := {vector}) (by decide)\n'
    pr+='    intro v hv\n    simp only [Finset.mem_insert, Finset.mem_singleton] at hv\n'
    pr+='    rcases hv with '+' | '.join(['rfl']*len(cyc))+' <;> assumption'
    add([-v for v in lits],pr)
assert clauses == archived, 'Reconstructed clause order differs from archived CNF'
assert nextvar == 156 and len(clauses)==321

preamble='''import Research.Erdos883.N12Certificate

/-!
# Symbolic verification of all 321 clauses of the archived n12 certificate

Generated by `scripts/generate_n12_bridge.py`. The generator is not trusted:
every leaf below is an ordinary Lean proof against the separately parsed,
unmodified DIMACS formula. No enumeration of all sets or n12 graph theorem is
used. Counter auxiliaries mean prefix counts, and the seven negative blocks
use Jentges's actual five-cycle witnesses.
-/

namespace Erdos883Research.N12Certificate
open SequentialCounter

private lemma pf4 : (4 : ℕ).primeFactors = {2} := by
  change (2 ^ 2 : ℕ).primeFactors = {2}
  exact Nat.primeFactors_prime_pow (by decide) Nat.prime_two

private lemma pf8 : (8 : ℕ).primeFactors = {2} := by
  change (2 ^ 3 : ℕ).primeFactors = {2}
  exact Nat.primeFactors_prime_pow (by decide) Nat.prime_two

private lemma pf9 : (9 : ℕ).primeFactors = {3} := by
  change (3 ^ 2 : ℕ).primeFactors = {3}
  exact Nat.primeFactors_prime_pow (by decide) Nat.prime_three

private lemma pf6 : (6 : ℕ).primeFactors = {2, 3} := by
  change (2 * 3 : ℕ).primeFactors = {2, 3}
  rw [Nat.primeFactors_mul (by decide) (by decide), Nat.prime_two.primeFactors,
    Nat.prime_three.primeFactors]
  decide

private lemma pf12 : (12 : ℕ).primeFactors = {2, 3} := by
  change (4 * 3 : ℕ).primeFactors = {2, 3}
  rw [Nat.primeFactors_mul (by decide) (by decide), pf4, Nat.prime_three.primeFactors]
  decide

private lemma pf10 : (10 : ℕ).primeFactors = {2, 5} := by
  change (2 * 5 : ℕ).primeFactors = {2, 5}
  rw [Nat.primeFactors_mul (by decide) (by decide), Nat.prime_two.primeFactors,
    (show Nat.Prime 5 by decide).primeFactors]
  decide

local macro "support_facts" : tactic => `(tactic|
  (simp only [pf4, pf8, pf9, pf6, pf12, pf10, Nat.primeFactors_one,
    Nat.prime_two.primeFactors, Nat.prime_three.primeFactors,
    (show Nat.Prime 5 by decide).primeFactors,
    (show Nat.Prime 7 by decide).primeFactors,
    (show Nat.Prime 11 by decide).primeFactors] <;> decide))

private theorem satisfies_and {v : Sat.Valuation} {f g : Sat.Fmla}
    (hf : v.satisfies_fmla f) (hg : v.satisfies_fmla g) :
    v.satisfies_fmla (Sat.Fmla.and f g) := by
  constructor
  intro c hc
  rcases List.mem_append.mp hc with hc | hc
  · exact hf.prop c hc
  · exact hg.prop c hc

private theorem satisfies_one {v : Sat.Valuation} {c : Sat.Clause}
    (hc : v.satisfies c) : v.satisfies_fmla (Sat.Fmla.one c) := by
  constructor
  intro d hd
  have hd : d = c := List.mem_singleton.mp hd
  exact hd ▸ hc

set_option maxRecDepth 10000 in
set_option maxHeartbeats 800000 in
theorem satisfies_formula (B : Finset ℕ)
    (hpos : prefixTrueCount (fun k => k + 1 ∈ B) 12 ≤ 9)
    (hneg : prefixTrueCount (fun k => k + 1 ∉ B) 12 ≤ 3)
    (hevens : ∀ v ∈ ({2, 4, 6, 8, 10, 12} : Finset ℕ), v ∈ B)
    (hs : ∀ x ∈ B, ∀ y ∈ Finset.Icc 1 12,
      x % 2 = y % 2 → x.primeFactors ⊂ y.primeFactors → y ∈ B)
    (hp : ∀ x ∈ B, ∀ y ∈ Finset.Icc 1 12,
      y < x → y.primeFactors = x.primeFactors → y ∈ B)
    (hfree : ¬ (SimpleGraph.cycleGraph 5).IsContained
      (coprimeGraph.induce (B : Set ℕ))) :
    (assignment B).satisfies_fmla formula := by
  unfold formula
'''

def tree(lo,hi,indent='  '):
    if hi-lo==1:
        # Expected type must be fixed to this exact archived clause before change.
        return indent+'apply satisfies_one\n'+indent+'-- DIMACS clause '+str(lo+1)+'\n'+ '\n'.join(indent+l for l in proofs[lo][3:].splitlines())+'\n'
    mid=lo+(hi-lo)//2
    return indent+'apply satisfies_and\n'+indent+'·\n'+tree(lo,mid,indent+'  ')+indent+'·\n'+tree(mid,hi,indent+'  ')
# Remove inherited indentation of proof body.
proofs=[p[:3]+'\n'.join(l[4:] if l.startswith('    ') else l for l in p[3:].splitlines()) for p in proofs]
DEST.write_text(preamble+tree(0,len(clauses))+'''
/-- End-to-end finite graph result using canonicalization and the archived LRAT.
No direct finite coverage table is imported. -/
theorem n12_b0_has_five_cycle_via_lrat (A : Finset ℕ)
    (hA : A ⊆ Finset.Icc 1 12) (hcard : A.card = 9)
    (heven : selectedCount (fun v => v % 2 = 0) A = 6) :
    (SimpleGraph.cycleGraph 5).IsContained (coprimeGraph.induce (A : Set ℕ)) := by
  classical
  by_contra hfree
  obtain ⟨B, hB, hBcard, hBeven, hBfree, hs, hp⟩ :=
    exists_compressed_prefix_counterexample (SimpleGraph.cycleGraph 5) 12 A hA hfree
  have hcB : B.card = 9 := hBcard.trans hcard
  have heB : selectedCount (fun v => v % 2 = 0) B = 6 := hBeven.trans heven
  have hsat := satisfies_formula B
    (by rw [total_mem B hB, hcB])
    (by rw [total_not_mem B hB hcB])
    (all_evens B hB heB) hs hp hBfree
  exact refutation (assignment B) hsat

end Erdos883Research.N12Certificate

#print axioms Erdos883Research.N12Certificate.satisfies_formula
#print axioms Erdos883Research.N12Certificate.n12_b0_has_five_cycle_via_lrat
''')
print(f'Generated {len(clauses)} symbolic clause proofs; exact DIMACS reconstruction matches.')
